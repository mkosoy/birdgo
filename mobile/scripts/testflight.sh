#!/usr/bin/env bash
set +x
set -euo pipefail

die() { printf 'TestFlight: %s\n' "$*" >&2; exit 1; }

ASC_PRIVATE_KEY_VALUE="${ASC_PRIVATE_KEY:-${ASC_API_KEY_P8:-}}"
for name in ASC_KEY_ID ASC_ISSUER_ID APPLE_TEAM_ID; do
    [[ -n "${!name:-}" ]] || die "Set $name before running this script."
done
[[ -n "$ASC_PRIVATE_KEY_VALUE" ]] || die "Set ASC_PRIVATE_KEY before running this script."
[[ "$APPLE_TEAM_ID" =~ ^[A-Z0-9]{10}$ ]] || die "APPLE_TEAM_ID must be a 10-character Apple team ID."
[[ "$ASC_KEY_ID" =~ ^[A-Za-z0-9]+$ ]] || die "ASC_KEY_ID must be alphanumeric."
[[ "$(uname -s)" == Darwin ]] || die "Archiving and uploading require macOS with Xcode."
command -v xcodebuild >/dev/null || die "Install and select Xcode."
command -v pod >/dev/null || die "Install CocoaPods before archiving."

mobile_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$mobile_dir"
[[ -f package.json && -f app.json ]] || die "Script must live in mobile/scripts."

if [[ ! -d node_modules/expo ]]; then
    npm ci
fi

build_number="${BUILD_NUMBER:-$(date +%s)}"
[[ "$build_number" =~ ^[1-9][0-9]*$ ]] || die "BUILD_NUMBER must be a positive integer."

# Generate the native project locally on the macOS builder. It is intentionally
# not committed; app.json remains the source of truth for the Expo config.
CI=1 npx expo prebuild --platform ios --clean --no-install

ios_dir="$mobile_dir/ios"
workspace="$ios_dir/BirdGo.xcworkspace"
scheme="BirdGo"
[[ -d "$ios_dir/BirdGo.xcodeproj" ]] || die "Expected Xcode project was not generated."
[[ -f "$ios_dir/BirdGo/Info.plist" ]] || die "Expected Info.plist was not generated."

export LANG=en_US.UTF-8
(cd "$ios_dir" && pod install)
[[ -d "$workspace" ]] || die "Expected workspace was not generated by pod install: $workspace"

archive_path="$ios_dir/BirdGo-$build_number.xcarchive"
[[ ! -e "$archive_path" ]] || die "Archive already exists: $archive_path"

umask 077
private_dir="$(mktemp -d "${TMPDIR:-/tmp}/birdgo-testflight.XXXXXXXX")"
trap 'rm -rf -- "$private_dir"' EXIT
trap 'exit 129' HUP
trap 'exit 130' INT
trap 'exit 143' TERM
key_path="$private_dir/AuthKey_${ASC_KEY_ID}.p8"
printf '%s\n' "$ASC_PRIVATE_KEY_VALUE" >"$key_path"
unset ASC_PRIVATE_KEY_VALUE ASC_PRIVATE_KEY ASC_API_KEY_P8
chmod 600 "$key_path"
umask 022

auth=(-allowProvisioningUpdates -authenticationKeyPath "$key_path"
    -authenticationKeyID "$ASC_KEY_ID" -authenticationKeyIssuerID "$ASC_ISSUER_ID")

plutil -replace CFBundleVersion -string "$build_number" "$ios_dir/BirdGo/Info.plist"
xcodebuild -workspace "$workspace" -scheme "$scheme" -configuration Release \
    -destination 'generic/platform=iOS' -archivePath "$archive_path" "${auth[@]}" \
    "CURRENT_PROJECT_VERSION=$build_number" "DEVELOPMENT_TEAM=$APPLE_TEAM_ID" \
    CODE_SIGN_STYLE=Automatic archive

options="$private_dir/ExportOptions.plist"
cat >"$options" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
    <key>method</key><string>app-store-connect</string>
    <key>destination</key><string>upload</string>
    <key>teamID</key><string>$APPLE_TEAM_ID</string>
    <key>signingStyle</key><string>automatic</string>
    <key>uploadSymbols</key><true/>
    <key>manageAppVersionAndBuildNumber</key><false/>
</dict></plist>
EOF
xcodebuild -exportArchive -archivePath "$archive_path" -exportOptionsPlist "$options" \
    -exportPath "$private_dir/export" "${auth[@]}"

printf 'TestFlight: uploaded BirdGo build %s\n' "$build_number"
